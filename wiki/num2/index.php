				<h1>NullMedia Bonus Features</h1>

				<p>
					This page lists extra formatting tools and shortcuts available inside NullMedia.
					They exist to make posting content slightly less painful than manually writing HTML like it’s 2003.
				</p>

				<h2>How to post images</h2>
				<p>
					Insert an image using:
					<code>&lt;img src="linkhere"&gt;&lt;br&gt;</code><br>
					You can also upload an image to GitHub and link it directly.
					A shortcut like Ctrl + Shift + I may insert a template automatically if supported.
				</p>

				<h2>How to make text bold</h2>
				<p>
					Wrap text in <code>&lt;b&gt;...&lt;/b&gt;</code> or use Ctrl + B.
					Because typing tags manually is apparently still a lifestyle choice.
				</p>

				<h2>How to make text italic</h2>
				<p>
					Use <code>&lt;i&gt;...&lt;/i&gt;</code> or press Ctrl + I.
					For when your words need emotional instability but in a classy way.
				</p>

				<h2>How to underline text</h2>
				<p>
					Use <code>&lt;u&gt;...&lt;/u&gt;</code> or Ctrl + U.
					Useful if you enjoy visual emphasis from the early internet era.
				</p>

				<h2>How to create a code block</h2>
				<p>
					Wrap content in <code>&lt;pre&gt;&lt;code&gt;...&lt;/code&gt;&lt;/pre&gt;</code><br>
					Or use Ctrl + Shift + C to insert a code block template.
					For when readability matters slightly more than suffering.
				</p>

				<h2>How to create a hyperlink</h2>
				<p>
					Use <code>&lt;a href="url"&gt;text&lt;/a&gt;</code> manually,<br>
					or press Ctrl + K to insert a link template with the cursor placed in the href field.
					Convenience, but still HTML under the hood like everything else.
				</p>

				<h2>How to create a blockquote</h2>
				<p>
					Use <code>&lt;blockquote&gt;...&lt;/blockquote&gt;</code><br>
					or press Ctrl + Q to insert it automatically.
					For when you need text to look more important than it actually is.
				</p>

				<h2>How to submit a post</h2>
				<p>
					Press Ctrl + Enter to submit a post instantly.
					Or click the submit button like a normal human being without keyboard theatrics.
				</p>

